import { afterEach, describe, expect, test } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { linkLaunchers, windowsShim } from "./launchers";
import { renameTokens, resolveAnchorSpellings } from "./loose-anchor";

const tempDirs: string[] = [];
const tempDir = async () => {
	const dir = await fs.mkdtemp(path.join(os.tmpdir(), "omp-zh regression % 中文 "));
	tempDirs.push(dir);
	return dir;
};
afterEach(async () => {
	await Promise.all(tempDirs.splice(0).map(dir => fs.rm(dir, { recursive: true, force: true })));
});

describe("anchor alternatives", () => {
	test("renames cannot cascade or replace larger identifiers", () => {
		expect(renameTokens("o=r;other=r2", new Map([["o", "r"], ["r", "s"]]))).toBe("r=s;other=r2");
		expect(renameTokens("a=b", new Map([["a", "b"], ["b", "a"]]))).toBe("b=a");
	});
	const primary = { find: "status(e,t){let s=this.ctx.children", replace: "status(e,t){e=translate(e);let s=this.ctx.children" };
	const alt = { find: 'status(e,t){let n=this.ctx.children,s={dim:t?.dim,label:"status"}', replace: 'status(e,t){e=translate(e);let n=this.ctx.children,s={dim:t?.dim,label:"status"}' };
	const code = 'status(e,t){let r=this.ctx.children,s={dim:t?.dim,label:"status"};return r}' +
		'other(e,t){let r=this.other.children;return r}';

	test("a unique renamed alternative wins over the broad primary", () => {
		expect(resolveAnchorSpellings(code, [primary])).toHaveLength(2);
		const hits = resolveAnchorSpellings(code, [primary, alt]);
		expect(hits).toHaveLength(1);
		expect(hits[0].replace).toBe('status(e,t){e=translate(e);let r=this.ctx.children,s={dim:t?.dim,label:"status"}');
	});
});

describe("launcher ownership", () => {
	test("repeat runs count and refresh generated CMD shims", async () => {
		const dir = await tempDir();
		const dest = path.join(dir, "omp-zh.cmd");
		await fs.writeFile(dest, '@echo off\r\nrem Generated by omp-zh. Older shim.\r\nbun old.js\r\n');
		expect(await linkLaunchers("unused", "new.js", "bun.exe", [dir], true)).toEqual([dest]);
		expect(await fs.readFile(dest, "utf8")).toBe(windowsShim("new.js", "bun.exe"));
		expect(await linkLaunchers("unused", "new.js", "bun.exe", [dir], true)).toEqual([dest]);
	});
	test("unrelated launchers are preserved", async () => {
		const dir = await tempDir();
		const dest = path.join(dir, "omp-zh.cmd");
		await fs.writeFile(dest, "@echo custom launcher");
		expect(await linkLaunchers("unused", "cli.js", "bun", [dir], true)).toEqual([]);
		expect(await fs.readFile(dest, "utf8")).toBe("@echo custom launcher");
	});
	test.skipIf(process.platform !== "win32")("CMD forwards arguments and exit codes with spaces, percent signs and Unicode paths", async () => {
		const dir = await tempDir();
		const cli = path.join(dir, "entry.js");
		const shim = path.join(dir, "omp-zh.cmd");
		await fs.writeFile(cli, "console.log(JSON.stringify(process.argv.slice(2))); process.exit(17);");
		await fs.writeFile(shim, windowsShim(cli, process.execPath));
		const proc = Bun.spawnSync([process.env.ComSpec ?? "cmd.exe", "/d", "/s", "/c", `""${shim}" "two words" "中文""`], {
			stdout: "pipe", stderr: "pipe", windowsVerbatimArguments: true,
		});
		expect(proc.stderr.toString()).toBe("");
		expect(proc.exitCode).toBe(17);
		expect(JSON.parse(proc.stdout.toString().trim())).toEqual(["two words", "中文"]);
	});
});

test("doctor inspects a missing binary sidecar without creating a runtime or launchers", async () => {
	const home = await tempDir();
	const proc = Bun.spawnSync([process.execPath, path.join(import.meta.dir, "..", "patch.ts"), "doctor"], {
		env: { ...process.env, HOME: home, USERPROFILE: home, APPDATA: path.join(home, "appdata"),
			OMP_PKG: process.execPath, OMP_ZH_NO_SIDECAR: "0" },
		stdout: "pipe", stderr: "pipe", timeout: 10_000,
	});
	expect(proc.exitCode).toBe(0);
	expect(proc.stdout.toString()).toContain(`install kind: sidecar (omp ${Bun.version})`);
	expect(proc.stdout.toString()).toContain("doctor is read-only");
	expect(proc.stderr.toString()).toBe("");
	// Bun itself may create its transpiler cache under .bun in the test home.
	expect((await fs.readdir(home)).filter(name => name !== ".bun")).toEqual([]);
});
